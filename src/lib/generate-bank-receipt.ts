import jsPDF from "jspdf";

export interface BankReceiptData {
  workerName: string;
  workerCpf: string;
  bankName?: string;
  bankCode?: string;
  agency?: string;
  accountNumber?: string;
  accountType?: string; // "corrente" | "poupanca"
  pixKeyType?: string;  // "cpf" | "telefone" | "email" | "aleatoria"
  pixKey?: string;
  holderName?: string;
  holderCpf?: string;
  isSelfHolder: boolean;
  generatedByUserName: string;
}

const PIX_KEY_TYPE_LABELS: Record<string, string> = {
  cpf: "CPF",
  telefone: "Telefone",
  email: "E-mail",
  aleatoria: "Chave aleatória",
};

const ACCOUNT_TYPE_LABELS: Record<string, string> = {
  corrente: "Conta Corrente",
  poupanca: "Conta Poupança",
};

export function generateBankReceipt(data: BankReceiptData): Blob {
  const doc = new jsPDF({ orientation: "portrait", unit: "mm", format: "a4" });
  const pageWidth = doc.internal.pageSize.getWidth();
  let y = 25;

  const addLine = (label: string, value: string | undefined | null) => {
    if (!value) return;
    doc.setFont("helvetica", "bold");
    doc.setFontSize(10);
    doc.text(`${label}:`, 20, y);
    doc.setFont("helvetica", "normal");
    doc.text(value, 70, y);
    y += 7;
  };

  // Title
  doc.setFont("helvetica", "bold");
  doc.setFontSize(16);
  doc.text("Comprovante de Dados Bancários", pageWidth / 2, y, { align: "center" });
  y += 8;

  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(120, 120, 120);
  doc.text("Gerado automaticamente pelo sistema", pageWidth / 2, y, { align: "center" });
  doc.setTextColor(0, 0, 0);
  y += 5;

  const now = new Date();
  doc.setFontSize(9);
  doc.text(
    `Data/hora de geração: ${now.toLocaleDateString("pt-BR")} ${now.toLocaleTimeString("pt-BR")}`,
    pageWidth / 2, y, { align: "center" }
  );
  y += 12;

  // Separator
  doc.setDrawColor(200, 200, 200);
  doc.line(20, y, pageWidth - 20, y);
  y += 10;

  // Worker section
  doc.setFont("helvetica", "bold");
  doc.setFontSize(12);
  doc.text("Dados do Trabalhador", 20, y);
  y += 8;

  addLine("Nome", data.workerName);
  addLine("CPF", data.workerCpf);
  y += 5;

  // Bank section
  doc.setFont("helvetica", "bold");
  doc.setFontSize(12);
  doc.text("Dados Bancários", 20, y);
  y += 8;

  if (data.pixKeyType || data.pixKey) {
    addLine("Tipo de chave Pix", data.pixKeyType ? PIX_KEY_TYPE_LABELS[data.pixKeyType] || data.pixKeyType : undefined);
    addLine("Chave Pix", data.pixKey);
  }

  addLine("Banco", data.bankName ? `${data.bankName}${data.bankCode ? ` (${data.bankCode})` : ""}` : undefined);
  addLine("Agência", data.agency);
  addLine("Conta", data.accountNumber);
  addLine("Tipo de conta", data.accountType ? ACCOUNT_TYPE_LABELS[data.accountType] || data.accountType : undefined);
  y += 5;

  // Holder section
  doc.setFont("helvetica", "bold");
  doc.setFontSize(12);
  doc.text("Titular da Conta", 20, y);
  y += 8;

  addLine("Nome do titular", data.holderName);
  addLine("CPF do titular", data.holderCpf);
  addLine("Relação", data.isSelfHolder ? "Próprio trabalhador" : "Terceiro");
  y += 10;

  // Separator
  doc.setDrawColor(200, 200, 200);
  doc.line(20, y, pageWidth - 20, y);
  y += 8;

  // Generated by
  doc.setFontSize(9);
  doc.setTextColor(100, 100, 100);
  doc.text(`Gerado por: ${data.generatedByUserName}`, 20, y);
  y += 12;

  // Footer
  doc.setFontSize(8);
  doc.setTextColor(150, 150, 150);
  doc.text(
    "Este documento foi gerado automaticamente e serve como registro interno dos dados bancários informados.",
    pageWidth / 2, pageWidth > 200 ? 280 : y + 10,
    { align: "center", maxWidth: pageWidth - 40 }
  );

  return doc.output("blob");
}
